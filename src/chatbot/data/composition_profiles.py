def find_composition_profile(comp_id_clean):
    """
    Find the matching composition profile by keyword matching.

    Args:
        comp_id_clean: Lowercased composition identifier string.

    Returns:
        The matching profile dict, or DEFAULT_COMPOSITION_PROFILE if none match.
    """
    for profile in COMPOSITION_PROFILES:
        if any(kw in comp_id_clean for kw in profile["keywords"]):
            return profile
    return DEFAULT_COMPOSITION_PROFILE
